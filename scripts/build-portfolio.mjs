import {createRequire} from 'node:module';
import {mkdir,writeFile,copyFile,cp} from 'node:fs/promises';
import path from 'node:path';
const root=process.cwd();
const pages=process.argv.includes('--github-pages');
const base=pages?'/portfolio-gabriel-liandro':'';
const output=pages?'docs':'dist';
const dependencies=process.env.PORTFOLIO_DEPS || root;
const require=createRequire(path.join(dependencies,'package.json'));
const {build}=require('esbuild');
const aliases=Object.fromEntries(['react','react-dom','lucide-react'].map(name=>[name,path.join(dependencies,'node_modules',name)]));
await mkdir(output,{recursive:true});
await mkdir('.sites-runtime',{recursive:true});
const shared={bundle:true,jsx:'automatic',alias:aliases,define:{'process.env.NODE_ENV':'"production"','__ASSET_BASE__':JSON.stringify(base)},logLevel:'info'};
await build({...shared,entryPoints:['app/client.tsx'],outfile:`${output}/app.js`,platform:'browser',minify:true});
await writeFile('.sites-runtime/render.tsx',`import React from 'react';import {renderToString} from 'react-dom/server';import Home from '../app/page';export const html=renderToString(<Home/>);`);
await build({...shared,entryPoints:['.sites-runtime/render.tsx'],outfile:'.sites-runtime/page.cjs',platform:'node',format:'cjs'});
const markup=createRequire(path.join(root,'package.json'))('./.sites-runtime/page.cjs').html;
await copyFile('app/globals.css',`${output}/style.css`);
await copyFile('public/favicon.svg',`${output}/favicon.svg`);
await cp('public/media',`${output}/media`,{recursive:true});
await writeFile(`${output}/.nojekyll`,'');
await writeFile(`${output}/index.html`,`<!doctype html><html lang="pt-BR"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="theme-color" content="#f3efe6"><title>Gabriel Luiz Liandro | Animações e sites com IA</title><meta name="description" content="Animações, vídeos e sites com inteligência artificial. Conheça os projetos de Gabriel Luiz Liandro."><link rel="icon" href="${base}/favicon.svg"><link rel="stylesheet" href="${base}/style.css"></head><body><div id="root">${markup}</div><script type="module" src="${base}/app.js"></script></body></html>`);
console.log(`Portfólio pronto em ${output}/`);
